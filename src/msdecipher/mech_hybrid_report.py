    L = ["# Hybrid generators: plaintext dependence + copy-and-modify word reuse vs MS 408", "",
         "_Auto-generated by `python -m msdecipher hybrid-run`. **MS 408 is undeciphered.** These generators are tests of whether combining two published "
         "ingredients repairs the metrics each parent misses; a reproduced metric shows that metric does not discriminate, not that the manuscript was made this way._", "",
         "## 1. Design", "",
         "Engine (`mech_hybrid.py`; a simplified Python copy-and-modify process, **not** the Timm & Schinner rule set): with probability `p_copy` copy a recent word "
         "(previous word with prob `p_prev`, else uniform over the last `window` words) and apply one operation (exact repeat `p_exact`, final-unit edit `p_suffix`, "
         "initial-unit edit `p_prefix`, inner-unit replacement = the rest); otherwise take the next word from the *encoder*. Max 3 identical repeats, ≤ 10 units. "
         "**6 fitted engine parameters.**", "",
         "| id | encoder (the plaintext-dependent part) | extra fitted parameters |", "|---|---|---|",
         "| A1 | Naibbe cipher tokens produced on the fly from Latin/Italian plaintext (1–2 letters per innovation); edit units drawn from the innovated words' own unit distributions | 0 |",
         "| A2 | whole-word codebook: every plaintext word type gets a fixed codeword sampled (invertibly) from a slot-conditioned-bigram grammar fitted on the *training types* | grammar parameters (counted) |",
         "| B (reverse) | copy-modify base (`p_copy ≥ 0.6`); every edit inserts the Naibbe glyph string of the next plaintext letter (prefix / suffix / unigram state, table by card draw); innovations are Naibbe tokens | 0 |",
         "| C0 (control) | same engine, innovations i.i.d. from the MS-fitted slot-conditioned-bigram grammar: **no plaintext** | grammar parameters (counted) |", "",
         "## 2. Protocol", "",
         f"* 3 folds by folio (folio *i* → fold *i* mod 3): fit on two folds' text, evaluate on the third. {len(fits.n_train.unique())} training sizes: {', '.join(f'{int(x):,}' for x in fits.n_train.unique())} tokens.",
         "* Fit objective: RMS z over 9 lexicon metrics + H1/h2/h3 (12 metrics); random search (120) + local refinement (3 × 30), 2 generator seeds per candidate; "
         "z-scale = sqrt(jackknife SE² + (2 % of value)²). **Every other suite metric (23) is never fitted.**",
         f"* Evaluation: best parameters, fresh seeds, {res['n_runs']} runs per model per fold (different plaintexts), generated at the held-out fold's size, full 35-metric suite, "
         "prediction-interval verdicts against the held-out fold (SE = delete-one-group jackknife).",
         "* Parents under the same protocol: Naibbe (78-card), Timm-Schinner (defaults; and parameters fitted earlier on **all** MS 408 → in-sample, favours the parent), "
         "slot-conditioned bigram trained on the training folds. Naibbe-live (A1/B) and `NaibbeCipher` share tables and rules.", "",
         "## 3. Fitted parameters and fit quality (training folds)", ""]
    ft = fits[["fold", "variant", "k_fitted", "distance", "median_random_distance", "p_copy", "window", "p_prev", "p_exact", "p_suffix", "p_prefix"]].copy()
    ft["variant"] = ft["variant"].map(SHORT)
    L += md(ft, 3) + ["", "`distance` = RMS z over the 12 fit metrics (lower is better); `median_random_distance` = median of the random-search candidates. "
                      "The all-MS 408 fits (used in step 2) are in `fits_all_ms408.csv`.", ""]
    sm = summary_by_model(ver, pen)
    sm["model"] = sm["model"].map(lambda x: SHORT.get(x, x))
    L += ["## 4. Held-out folios: how many of the 35 suite metrics are reproduced", "",
          "Mean over the 3 folds. `repro_unfitted` counts only the 23 metrics that were never in the fit objective.", ""]
    L += md(sm, 2) + [""]
    L += ["## 5. Parameter-count-penalised comparison", "",
          "`AIC_train = chi2_train(fit metrics) + 2 k`, k = fitted parameters (engine parameters + any grammar parameters that draw words from MS 408; Naibbe has none, the Java "
          "self-citation generator 15 swept options when fitted). `chi2_heldout` is the same χ² on the held-out folio set (no fitting there). "
          "With only 12 fitted-on metrics, any k ≳ 12 is a model that can in principle match every fitted number — the penalty makes that visible, "
          "it does not make the comparison 'significant'.", ""]
    pt = pen.groupby("model", sort=False)[["k_fitted", "chi2_train_fitset", "AIC_train", "chi2_heldout_fitset", "repro_unfitted", "rms_z_unfitted_cap10"]].mean().reset_index()
    pt["model"] = pt["model"].map(lambda x: SHORT.get(x, x))
    L += md(pt, 1) + [""]
    L += ["## 6. Which metrics are reproduced (folds in which MS 408 lies inside the prediction interval; ↑/↓ = MS 408 above/below the model)", ""]
    L += md(key_matrix(ver)) + ["", "Model means on the same metrics (mean over folds):", ""] + md(key_values(ver)) + [""]
