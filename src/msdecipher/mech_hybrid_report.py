    sc["unfitted_reproduced"] = [int(((full[(full.mechanism == m)].verdict == "≈") & ~full[(full.mechanism == m)].metric.isin(
        R.FIT_METRICS + ["unit_H1", "unit_h2", "unit_h3"])).sum()) for m in sc.mechanism]
