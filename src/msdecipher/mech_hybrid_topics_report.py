STATS = [("js_excess", "JS excess over null (bits)", "js_se"), ("nb_bal_acc", "NB balanced accuracy (held-out folios)", "nb_bal_acc_se"),
         ("lr_bal_acc", "LR balanced accuracy (held-out folios)", "lr_bal_acc_se"), ("keyword_overlap", "section-keyword split-half overlap", "keyword_se")]


def gen_table(res: dict) -> pd.DataFrame:
    ms, unc, gen = res["ms"], res["unc"], res["gen"]
    rows = []
    for m in T.MODELS:
        g = gen[gen.model == m]
        r = {"model": T.LABEL[m], "n": len(g)}
        for col, lab, sek in STATS:
            v = CI.interval_verdict(float(ms[col]), unc.get(sek), g[col].astype(float).tolist())
            r[lab] = f"{g[col].mean():.3f} ± {g[col].std(ddof=1):.3f} {v['verdict']}"
        r["seeds with NB perm p<0.05"] = f"{int((g.nb_p < 0.05).sum())}/{len(g)}"
        rows.append(r)
    return pd.DataFrame(rows)


def findings(res: dict) -> list[str]:
    ms, gen = res["ms"], res["gen"]
    L = []
    mean = lambda m, c: float(gen[gen.model == m][c].mean())     # noqa: E731
    L.append(f"* MS 408: between-section JS {ms['js']:.3f} bits (null mean {ms['js_null_mean']:.3f}, z = {ms['js_z']:.1f}, permutation p = {ms['js_p']:.4f}); NB balanced accuracy "
             f"{ms['nb_bal_acc']:.3f} (null mean {ms['nb_null_mean']:.3f}, p = {ms['nb_p']:.4f}; chance = {1 / len(res['classes']):.2f}); LR {ms['lr_bal_acc']:.3f}; "
             f"keyword overlap {ms['keyword_overlap']:.3f} (null {ms['keyword_null_mean']:.3f}). So the section signal is real and large in this transcription.")
    for tag, a, b in (("A1 (Naibbe tokens + copy-modify)", "A1|matched", "A1|mixed"), ("A2 (codebook + copy-modify)", "A2|matched", "A2|mixed"),
                      ("B (reverse)", "B|matched", "B|mixed"), ("pure Naibbe cipher", "Naibbe pure|matched", "Naibbe pure|mixed")):
        L.append(f"* {tag}: NB balanced accuracy {mean(a, 'nb_bal_acc'):.3f} with topic-matched plaintext vs {mean(b, 'nb_bal_acc'):.3f} with topic-mixed "
                 f"(MS 408 {ms['nb_bal_acc']:.3f}); JS excess {mean(a, 'js_excess'):.3f} vs {mean(b, 'js_excess'):.3f} (MS {ms['js_excess']:.3f}).")
    L.append(f"* Pure generators on the same folio layout (no plaintext): C0 NB accuracy {mean('C0|none', 'nb_bal_acc'):.3f}, self-citation (Java) defaults "
             f"{mean('SC defaults', 'nb_bal_acc'):.3f}, fitted {mean('SC fitted', 'nb_bal_acc'):.3f}; JS excess {mean('C0|none', 'js_excess'):.3f} / "
             f"{mean('SC defaults', 'js_excess'):.3f} / {mean('SC fitted', 'js_excess'):.3f}. These measure how much section signal copying/drift alone produces "
             "(sections are contiguous runs of folios).")
    return L


